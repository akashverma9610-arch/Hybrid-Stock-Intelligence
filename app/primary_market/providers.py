from typing import Protocol
from app.primary_market.models import IssueSubscriptionSnapshot,PrimaryMarketIssue
class PrimaryMarketDataProvider(Protocol):
 """Provider-neutral primary-market contract; V1 is supplied/offline only."""
 def list_issues(self,*,start,end)->tuple[PrimaryMarketIssue,...]:...
 def get_subscription_snapshots(self,issue_id:str)->tuple[IssueSubscriptionSnapshot,...]:...
 def get_issue_details(self,issue_id:str)->PrimaryMarketIssue|None:...
